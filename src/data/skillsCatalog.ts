export const ALL_SKILL_CATEGORIES: SkillCategoryDefinition[] = [
  ...TECHNICAL_SKILL_CATEGORIES,
  ...NON_TECHNICAL_SKILL_CATEGORIES,
];

export interface FlattenedSkillEntry {
  name: string;
  normalized: string;
  kind: SkillKind;
  categoryId: string;
  categoryLabel: string;
  isCustom?: boolean;
}

function buildUniqueFlattenedSkills(): FlattenedSkillEntry[] {
  const seen = new Map<string, FlattenedSkillEntry>();
  for (const cat of ALL_SKILL_CATEGORIES) {
    for (const skill of cat.skills) {
      const normalized = skill.trim().toLowerCase();
      if (!seen.has(normalized)) {
        seen.set(normalized, {
          name: skill.trim(),
          normalized,
          kind: cat.kind,
          categoryId: cat.id,
          categoryLabel: cat.label,
        });
      }
    }
  }
  return Array.from(seen.values());
}

export const ALL_PREDEFINED_SKILLS: FlattenedSkillEntry[] = buildUniqueFlattenedSkills();

export const PREDEFINED_TECHNICAL_SKILL_SET = new Set(
  ALL_PREDEFINED_SKILLS.filter((s) => s.kind === 'technical').map((s) => s.normalized)
);

export const PREDEFINED_NON_TECHNICAL_SKILL_SET = new Set(
  ALL_PREDEFINED_SKILLS.filter((s) => s.kind === 'non_technical').map((s) => s.normalized)
);
